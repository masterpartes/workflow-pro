-- 004_part_weight.sql
-- Peso tipico por descripcion, para la pierna Miami -> Quito, que se factura
-- SOBRE PESO REAL (no volumetrico).
--
-- Derivado de 1.548 items reales de DESPACHO MASTERPARTES.xlsx cuyos pesos por
-- linea cuadran con el total de su embarque. Se usa la MEDIANA, no el promedio:
-- los pesos son sesgados y una sola linea pesada corre el promedio.
--
-- La clave es el SUSTANTIVO PRINCIPAL de la descripcion, nunca un modificador.
-- "CERRADURA DE PUERTA" es una cerradura, no una puerta: casar el modificador
-- le daria 30 kg a una pieza de 0,5 kg. Ese error se detecto y se corrigio.
--
-- confianza:  alta  n>=4 y dispersion p75/p25 <= 2.5
--             media n>=3 y dispersion <= 3.5
--             baja  n>=2 y dispersion <= 8      <- mostrar SIEMPRE como dudoso
-- Sin clave -> no se estima nada, se escala al dueno.
--
-- Recalibrar: poner un despacho mas nuevo en workflow-pro y regenerar.

CREATE TABLE IF NOT EXISTS "part_weight" (
  clave        text PRIMARY KEY,
  palabras     smallint NOT NULL,
  peso_kg      numeric  NOT NULL,
  n_muestras   integer  NOT NULL,
  dispersion   numeric  NOT NULL,
  confianza    text     NOT NULL CHECK (confianza IN ('alta','media','baja')),
  updated_at   timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS "part_alias" (
  abreviatura  text PRIMARY KEY,
  canonico     text NOT NULL
);

